/**
 * Writes FINDINGS.md: the Global search's new analog candidates for every Moon and Mars site,
 * with a validation check against the analogs agencies already use.   npm run findings
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { decodeEarthGrid, findCandidates, screen, screenConfidence, validate, SCREENED, type GridMeta } from '../src/lib/earthGrid'
import { TARGETS } from '../src/data/targets'
import { EARTH_SITES } from '../src/data/earthSites'
import { IMPACTS } from '../src/data/impacts'
import { FACTOR_LABELS, WORLD_LABEL, type FactorKey } from '../src/data/types'
import { rankTwins } from '../src/lib/twins'
import { factorSimilarity } from '../src/lib/scoring'
import { distanceKm } from '../src/lib/geo'
import { APP_NAME } from '../src/brand'
import { ordinal } from '../src/lib/format'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const meta = JSON.parse(readFileSync(resolve(root, 'public/data/earth-grid.json'), 'utf8')) as GridMeta
const g = decodeEarthGrid(meta, new Uint8Array(readFileSync(resolve(root, 'public/data/earth-grid.bin'))))
const L: string[] = []
const pct = (p: number) => ordinal(p * 100)

L.push(`# Findings: new Earth analog candidates for the Moon Base and Mars`, '')
L.push(`Generated by ${APP_NAME}'s Global search on ${new Date().toISOString().slice(0, 10)} (grid built ${meta.built}). Regenerate with \`npm run findings\`.`, '')
L.push('## Method', '')
L.push(`All ${meta.land.toLocaleString('en-US')} land cells on Earth (0.5°, about 55 km) were scored against each Moon and Mars site with the app's Analog Similarity Index, using the ${SCREENED.length} factors open global maps provide: climate-zone proxies for dryness, cold, temperature swing, ground ice and bare ground (Köppen-Geiger, Rubel et al.), remoteness (GeoNames towns of 1,000+ people), impact structures (Earth Impact Database), young volcanoes (Smithsonian GVP), salt flats (Natural Earth) and low polar Sun (computed). Candidates are the best cells at least 300 km from every analog already listed in the app and 450 km from each other. Slope, highland rock (anorthosite) and caves are not screened globally: each candidate needs a live probe (NASA POWER, ESA Copernicus DEM, NASA MODIS, Macrostrat) and, ideally, a field visit.`, '')
L.push('## Validation: do known analogs rank highly?', '')
L.push('For each site, the five best known analogs (by the app\'s curated data) were located in the screening. A high percentile means the global screening independently agrees with where agencies already train.', '')
L.push('| World | Site | Profile screened | Known analogs, median percentile | Known analogs (percentile) |', '|---|---|---|---|---|')
const results = TARGETS.map(t => {
  const s = screen(g, t)
  const known = rankTwins(t, EARTH_SITES).filter(r => r.site.status === 'known').slice(0, 5).map(r => r.site)
  return { t, s, v: validate(g, s, known), c: findCandidates(g, s, EARTH_SITES, 5) }
})
for (const { t, v } of results) L.push(`| ${WORLD_LABEL[t.world]} | ${t.name} | ${Math.round(screenConfidence(t) * 100)}% | ${pct(v.median)} | ${v.rows.map(r => `${r.name.split(',')[0]} (${pct(r.percentile)})`).join(', ')} |`)
L.push('')
for (const { t, s, c } of results) {
  L.push(`## ${t.name} (${WORLD_LABEL[t.world]})`, '')
  const parts = (Object.entries(t.profile) as [FactorKey, number][]).filter(([k]) => SCREENED.includes(k) && t.factors[k] != null)
  L.push('| # | Candidate | Lat, lon | Score | Climate zone | Why it scores | Notes |', '|---|---|---|---|---|---|---|')
  c.forEach((x, i) => {
    const why = parts.map(([k, w]) => ({ k, v: w * factorSimilarity(g.values[k][x.cell], t.factors[k]!) })).sort((a, b) => b.v - a.v).slice(0, 3).map(p => FACTOR_LABELS[p.k].toLowerCase())
    const notes: string[] = []
    const crater = IMPACTS.filter(m => distanceKm(m, x) < m.km / 2 + 60).sort((a, b) => b.km - a.km)[0]
    if (crater) notes.push(`contains the ${crater.name} impact structure (${crater.km} km)`)
    if (g.values.basalt[x.cell] >= 0.6) notes.push('young volcanoes nearby')
    if (g.values.sediment[x.cell] >= 1) notes.push('salt flat')
    notes.push(`${Math.round(x.nearestListed?.km ?? 0).toLocaleString('en-US')} km from ${x.nearestListed?.name.split(',')[0]}`)
    L.push(`| ${i + 1} | ${x.name} | ${x.lat.toFixed(2)}, ${x.lon.toFixed(2)} | ${s[x.cell].toFixed(0)} | ${x.climate} | ${why.join(', ')} | ${notes.join('; ')} |`)
  })
  L.push('')
}
L.push('## Limitations', '')
L.push('- Climate-zone values are proxies for a whole cell, not measurements at a point; a candidate may hide a wetter valley or a town.')
L.push('- Some impact structures are buried under ice, sediment or sea (for example Hiawatha lies beneath the Greenland ice sheet), so check what is visible at the surface before planning a visit.')
L.push('- Only Holocene volcanoes are listed, so older lava fields can be missed; only mapped salt flats count as salts.')
L.push('- Lunar highland rock (anorthosite), slopes and caves are invisible to the screening. For the south-pole sites, the anorthosite crater at Kamestastin (already listed) remains the stand-out geology analog.')
L.push('- Next step for every candidate: probe it live in the app, then check imagery, access and permits before any field visit.', '')
writeFileSync(resolve(root, 'FINDINGS.md'), L.join('\n'))
console.log(`Wrote FINDINGS.md: ${results.length} sites, ${results.reduce((n, r) => n + r.c.length, 0)} candidates`)
