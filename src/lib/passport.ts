/**
 * Analog Passport: a portable characterization report for one Earth site.
 * Markdown for people (opens in any editor, renders on GitHub) and JSON for tools.
 * Pure text builders, plus a tiny browser download helper.
 */
import type { EarthSite, PlanetTarget } from '../data/types'
import { FACTOR_KEYS, FACTOR_LABELS, PROCESS_LABELS, WORLD_LABEL } from '../data/types'
import { TARGETS } from '../data/targets'
import { sourceById } from '../data/sources'
import { GAPS } from '../data/gaps'
import { planCampaign, rankTwins, sharedProcesses } from './twins'
import { lightWindows, lunarMaxSun } from './sun'
import { fmtCoords } from './format'

export interface Match { target: PlanetTarget; asi: number; confidence: number }

/** How well this site rehearses every Moon and Mars target, best first. */
export function matchesFor(site: EarthSite, targets: PlanetTarget[] = TARGETS): Match[] {
  return targets
    .map(t => {
      const r = rankTwins(t, [site])[0]
      return r ? { target: t, asi: r.result.asi!, confidence: r.result.confidence } : null
    })
    .filter((m): m is Match => !!m)
    .sort((a, b) => b.asi - a.asi)
}

const STATUS = { known: 'Established analog', candidate: 'New or under-used candidate', local: 'Malaysian comparison site', discovery: 'Live field probe (new)' } as const

export function passportMarkdown(site: EarthSite, appName: string, date = new Date()): string {
  const lines: string[] = []
  const matches = matchesFor(site)
  const pole = TARGETS.find(t => t.id === 'shackleton')!
  const windows = lightWindows(site.lat)
  const ridge = lightWindows(site.lat, lunarMaxSun(pole.lat))
  lines.push(`# Analog Passport: ${site.name}`)
  lines.push('')
  lines.push(`Generated by ${appName} on ${date.toISOString().slice(0, 10)} (NASA Space Apps Challenge 2026).`)
  lines.push('')
  lines.push(`- **Location:** ${fmtCoords(site.lat, site.lon, 3)}, ${site.country}`)
  lines.push(`- **Status:** ${STATUS[site.status]}`)
  lines.push(`- **Environment:** ${site.environment}`)
  if (site.analogUse) lines.push(`- **Space analog use so far:** ${site.analogUse}`)
  if (site.processes?.length) lines.push(`- **Processes at work (team reading of published descriptions):** ${site.processes.map(p => PROCESS_LABELS[p]).join('; ')}`)
  lines.push('')
  lines.push(site.description)
  lines.push('')
  lines.push('## Characterization')
  lines.push('')
  lines.push('Each factor runs from 0 to 1, where 1 means as Moon- or Mars-like as anywhere on Earth gets.')
  lines.push('')
  lines.push('| Factor | Value | Measurement | Source | Estimate? |')
  lines.push('|---|---|---|---|---|')
  for (const k of FACTOR_KEYS) {
    const f = site.factors[k]
    const src = sourceById(f.sourceId)?.name ?? f.sourceId
    lines.push(`| ${FACTOR_LABELS[k]} | ${f.value == null ? 'no data' : f.value.toFixed(2)} | ${f.raw.replace(/\|/g, '/')} | ${src} | ${f.estimate ? 'yes' : 'no'} |`)
  }
  lines.push('')
  lines.push('## Best Moon and Mars matches')
  lines.push('')
  lines.push('| World | Base or landing site | Analog Similarity Index | Data confidence | Shared processes |')
  lines.push('|---|---|---|---|---|')
  for (const m of matches) lines.push(`| ${WORLD_LABEL[m.target.world]} | ${m.target.name} | ${m.asi} | ${Math.round(m.confidence * 100)}% | ${sharedProcesses(site, m.target).map(p => PROCESS_LABELS[p]).join('; ') || (site.processes ? 'none' : 'not assessed')} |`)
  lines.push('')
  lines.push('## South-pole light calendar')
  lines.push('')
  if (windows.length) {
    lines.push(`Days when the Sun stays below 7° all day here (like the lunar south polar rims): ${windows.map(w => w.label).join('; ')}.`)
    lines.push(ridge.length
      ? `Days when it stays as low as at the Moon Base ridge (below ${lunarMaxSun(pole.lat).toFixed(1)}°): ${ridge.map(w => w.label).join('; ')}.`
      : `The Sun never stays as low as at the Moon Base ridge (below ${lunarMaxSun(pole.lat).toFixed(1)}°) here.`)
  } else {
    lines.push('The noon Sun is always higher than 7° here, so south-pole lighting needs artificial lights.')
  }
  lines.push('')
  lines.push('## What this site cannot simulate')
  lines.push('')
  for (const g of GAPS) lines.push(`- **${g.label}:** Earth ${g.earth}; Moon ${g.moon}; Mars ${g.mars}. Instead: ${g.instead}`)
  lines.push('')
  lines.push('## Sources')
  lines.push('')
  const ids = [...new Set(FACTOR_KEYS.map(k => site.factors[k].sourceId))]
  for (const id of ids) { const s = sourceById(id); if (s) lines.push(`- ${s.name} (${s.agency}): ${s.url}`) }
  lines.push('')
  lines.push('Values marked as estimates are team readings of the cited datasets, not field measurements. This is an educational screening tool, not a mission-planning product.')
  lines.push('')
  return lines.join('\n')
}

export function passportJson(site: EarthSite, appName: string, date = new Date()) {
  return {
    generator: appName,
    generated: date.toISOString(),
    site: { id: site.id, name: site.name, country: site.country, lat: site.lat, lon: site.lon, status: site.status, environment: site.environment, analogUse: site.analogUse ?? null, processes: site.processes ?? null },
    factors: Object.fromEntries(FACTOR_KEYS.map(k => [k, { ...site.factors[k], label: FACTOR_LABELS[k] }])),
    matches: matchesFor(site).map(m => ({ world: m.target.world, target: m.target.id, name: m.target.name, asi: m.asi, confidence: Number(m.confidence.toFixed(3)) })),
    lightWindows: lightWindows(site.lat).map(w => w.label),
  }
}

export const slug = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'site'

/** Saves text as a file in the browser. */
export function download(filename: string, text: string, type = 'text/markdown') {
  const blob = new Blob([text], { type: `${type};charset=utf-8` })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

/** A briefing for one Moon or Mars site: its best Earth twins, a field campaign and the gaps. */
export function twinReportMarkdown(t: PlanetTarget, sites: EarthSite[], appName: string, date = new Date()): string {
  const rows = rankTwins(t, sites).slice(0, 10)
  const plan = planCampaign(t, sites, 3)
  const L: string[] = []
  L.push(`# Earth twins for ${t.name} (${WORLD_LABEL[t.world]})`)
  L.push('')
  L.push(`Generated by ${appName} on ${date.toISOString().slice(0, 10)} (NASA Space Apps Challenge 2026).`)
  L.push('')
  L.push(`- **Location:** ${t.approx ? 'about ' : ''}${fmtCoords(t.lat, t.lon)}${t.program ? `; ${t.program}` : ''}`)
  L.push(`- **What matters for a crew here:** ${Object.entries(t.profile).map(([k, w]) => `${FACTOR_LABELS[k as keyof typeof FACTOR_LABELS]} ${Math.round((w ?? 0) * 100)}%`).join(', ')}`)
  L.push('')
  L.push(t.description)
  L.push('')
  L.push('## Best single Earth twins')
  L.push('')
  if (t.processes?.length) { L.push(`Processes at work at ${t.name}: ${t.processes.map(p => PROCESS_LABELS[p]).join('; ')}.`); L.push('') }
  L.push('| Rank | Site | Country | Status | Analog Similarity Index | Data confidence | Shared processes |')
  L.push('|---|---|---|---|---|---|---|')
  rows.forEach((r, i) => L.push(`| ${i + 1} | ${r.site.name} | ${r.site.country} | ${STATUS[r.site.status]} | ${r.result.asi} | ${Math.round(r.result.confidence * 100)}% | ${sharedProcesses(r.site, t).map(p => PROCESS_LABELS[p]).join('; ') || (r.site.processes ? 'none' : 'not assessed')} |`))
  L.push('')
  L.push('## Best three-site field campaign')
  L.push('')
  if (plan.single) L.push(`The best single site, ${plan.single.site.name}, covers ${Math.round(plan.single.coverage * 100)}% of what this site needs. These sites together cover ${Math.round(plan.coverage * 100)}%:`)
  L.push('')
  for (const s of plan.sites) {
    const roles = plan.factors.filter(f => f.siteId === s.id).map(f => FACTOR_LABELS[f.key])
    L.push(`- **${s.name}, ${s.country}**: best for ${roles.length ? roles.join(', ') : 'backup coverage'}`)
  }
  L.push('')
  L.push('## What no place on Earth can copy')
  L.push('')
  for (const g of GAPS) L.push(`- **${g.label}:** Earth ${g.earth}; ${WORLD_LABEL[t.world]} ${t.world === 'moon' ? g.moon : g.mars}. Instead: ${g.instead}`)
  L.push('')
  L.push('## Sources')
  L.push('')
  for (const id of t.sourceIds) { const s = sourceById(id); if (s) L.push(`- ${s.name} (${s.agency}): ${s.url}`) }
  L.push('')
  return L.join('\n')
}
